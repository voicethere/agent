export function isStopWord(token: string): boolean {
  const t = token
    .toLowerCase()
    .replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, "");
  return t === "" || STOP_WORDS.has(t);
}
